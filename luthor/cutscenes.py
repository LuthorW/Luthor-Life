class Cutscene(ui.Modal):
    def __init__(self, game, scene, on_end=None):
        self.g = game
        self.scene = scene
        self.steps = list(scene["steps"])
        self.on_end = on_end
        self.npc = scene.get("npc")
        self.i = 0
        self.map = game.world[scene["map"]]
        self.minutes = scene.get("time", game.minutes)
        self.weather = scene.get("weather", "sol")
        self.actors = {}
        self.cam = [0.0, 0.0]
        self.cam_target = None
        self.follow = None
        self.wait_cam = False
        self.bars = 0.0
        self.fade = 1.0
        self.fade_dir = 0
        self.after_fade = None
        self.wait = 0.0
        self.wait_actor = None
        self.sub = None
        self.caption = None
        self.photo = None
        self.fx = SceneFx()
        self.ask_skip = False
        self.kiss = None
        self.finished = False
        self.t = 0.0
        game.ambient.reset()

    # ----- câmera
    def tile_cam(self, x, y):
        vw, vh = self.g.view_size(self.map)
        cx = (x + 0.5) * TILE - vw / 2
        cy = (y + 0.5) * TILE - vh / 2
        return self.clamp(cx, cy)

    def clamp(self, cx, cy):
        vw, vh = self.g.view_size(self.map)
        mw, mh = self.map.w * TILE, self.map.h * TILE
        cx = (mw - vw) / 2 if mw <= vw else min(max(cx, 0), mw - vw)
        cy = (mh - vh) / 2 if mh <= vh else min(max(cy, 0), mh - vh)
        return [cx, cy]

    # ----- execução
    def blocked(self):
        if self.sub or self.wait > 0 or self.fade_dir or self.photo or self.ask_skip or self.kiss:
            return True
        if self.caption and self.caption["t"] > 0:
            return True
        if self.wait_actor and self.wait_actor.path:
            return True
        if self.wait_cam and self.cam_target:
            return True
        return False

    def run_steps(self):
        while not self.blocked() and not self.finished:
            if self.i >= len(self.steps):
                self.finish()
                return
            step = self.steps[self.i]
            self.i += 1
            self.exec(step)

    def speaker(self, name, mood=None):
        if name == "player":
            from .game import MOOD_ALIASES
            fname = art.portrait_file("leticia", MOOD_ALIASES.get(mood, mood)) or PLAYER_PORTRAIT
            return PLAYER_NAME, art.portrait(fname, PLAYER_LOOK, art.PORTRAIT_SIZE), "Letícia Luthor"
        d = NPCS[name]
        return d["name"], None, d["role"]

    def exec(self, step):
        cmd, args = step[0], step[1:]
        if cmd == "ator":
            name, x, y, d = args
            self.actors[name] = Actor(name, x, y, d, self.map.name)
        elif cmd == "sai":
            self.actors.pop(args[0], None)
        elif cmd in ("andar", "andar_"):
            a = self.actors.get(args[0])
            if a:
                a.walk_to(args[1], args[2])
                if cmd == "andar":
                    self.wait_actor = a
        elif cmd == "virar":
            a = self.actors.get(args[0])
            if a:
                a.dir = args[1]
        elif cmd == "pulo":
            a = self.actors.get(args[0])
            if a:
                a.hop = 0.45
        elif cmd == "emote":
            a = self.actors.get(args[0])
            if a:
                a.emote, a.emote_t = args[1], 1.8
            self.wait = 0.7
        elif cmd == "fala":
            name, txt = args[0], args[1]
            mood = args[2] if len(args) > 2 else None
            spk, portrait, sub = self.speaker(name, mood)
            if portrait is None:
                portrait = self.g.portrait_for(self.g.npcs[name], mood)
            self.sub = ui.Dialog(spk, [txt], portrait, subtitle=sub)
        elif cmd == "narra":
            self.sub = ui.Dialog("", [args[0]])
        elif cmd == "escolha":
            question, options = args[0], args[1]

            def pick(i, options=options):
                txt, pts, reply = options[i][:3]
                if self.npc and pts:
                    self.g.add_friendship(self.npc, pts)
                if reply and self.npc:
                    # 4º item opcional: o humor do retrato na resposta ("happy", "mad", "love"...);
                    # sem ele: 50+ pontos = love (tímido), acima de 0 = happy, negativo = mad, 0 = normal
                    if len(options[i]) > 3:
                        mood = options[i][3]
                    else:
                        mood = "love" if pts >= 50 else ("happy" if pts > 0 else ("mad" if pts < 0 else None))
                    self.steps.insert(self.i, ("fala", self.npc, reply, mood))
            self.sub = ui.Choice(question, [o[0] for o in options], pick)
        elif cmd == "camera":
            self.cam_target = self.tile_cam(args[0], args[1])
            self.follow = None
            self.wait_cam = True
        elif cmd == "camera_ja":
            self.cam = self.tile_cam(args[0], args[1])
            self.cam_target = None
            self.follow = None
        elif cmd == "seguir":
            self.follow = args[0]
        elif cmd == "mapa":
            def swap(name=args[0], tm=args[1] if len(args) > 1 else None):
                self.map = self.g.world[name]
                self.actors = {}
                self.follow = None
                self.cam_target = None
                if tm is not None:
                    self.minutes = tm
                self.g.ambient.reset()
            self.fade_dir = 1
            self.after_fade = swap
        elif cmd == "hora":
            self.minutes = args[0]
        elif cmd == "legenda":
            self.caption = dict(text=args[0], t=args[1] if len(args) > 1 else 2.5, total=args[1] if len(args) > 1 else 2.5)
        elif cmd == "foto":
            foto = art.resolve_photo(args[0])
            if foto:
                self.photo = art.portrait(foto, PLAYER_LOOK, 420)
        elif cmd == "efeito":
            kind, secs = args[0], args[1] if len(args) > 1 else 2.5
            if self.actors:
                xs = [a.center[0] for a in self.actors.values()]
                ys = [a.center[1] for a in self.actors.values()]
                cx, cy = sum(xs) / len(xs), sum(ys) / len(ys) - TILE
            else:
                vw, vh = self.g.view_size(self.map)
                cx, cy = self.cam[0] + vw / 2, self.cam[1] + vh / 2
            self.fx.add(kind, secs, cx, cy)
        elif cmd == "beijo":
            self.start_kiss(args[0], args[1])
        elif cmd == "esperar":
            self.wait = args[0]
        elif cmd == "fade_in":
            self.fade_dir = -1
        elif cmd == "fade_out":
            self.fade_dir = 1

    # ----- beijo: chegam lado a lado, se inclinam, estalinho e corações; depois ficam pertinho
    KISS_WALK, KISS_LEAN, KISS_HOLD, KISS_BACK = 0.6, 0.35, 1.2, 0.4

    def start_kiss(self, n1, n2):
        a, b = self.actors.get(n1), self.actors.get(n2)
        if not a or not b:
            return
        if b.name == "player":                        # a linha do beijo é a da outra personagem
            a, b = b, a
        row = b.fy
        mx = (a.fx + b.fx) / 2
        left, right = (a, b) if (a.fx, a.name != "player") <= (b.fx, b.name != "player") else (b, a)
        self.kiss = dict(t=0.0, left=left, right=right, mx=mx, row=row, smack=False,
                         start={left: (left.fx, left.fy), right: (right.fx, right.fy)})
        left.path, right.path = [], []

    def update_kiss(self, dt):
        k = self.kiss
        k["t"] += dt
        t, mx, row = k["t"], k["mx"], k["row"]
        W, L, H, B = self.KISS_WALK, self.KISS_LEAN, self.KISS_HOLD, self.KISS_BACK
        if t < W:                                     # andam até ficar uma de frente para a outra
            e = t / W
            gap, walking = 0.5, True
        elif t < W + L:
            e, walking = 1.0, False
            gap = 0.5 - 0.25 * math.sin((t - W) / L * math.pi / 2)
        elif t < W + L + H:
            e, walking, gap = 1.0, False, 0.25
        else:
            e, walking = 1.0, False
            gap = 0.25 + 0.2 * math.sin(min(1.0, (t - W - L - H) / B) * math.pi / 2)
        for actor, side in ((k["left"], -1), (k["right"], 1)):
            sx, sy = k["start"][actor]
            actor.fx = sx + (mx + side * gap - sx) * e
            actor.fy = sy + (row - sy) * e
            actor.dir = "right" if side < 0 else "left"
            if walking and (abs(sx - (mx + side * gap)) > 0.05 or abs(sy - row) > 0.05):
                actor.moving = True
                actor.anim += dt * 7
        hx = (mx + 0.5) * TILE
        hy = (row + 1) * TILE - FOOT - 34 * SCALE
        if not k["smack"] and t >= W + L:
            k["smack"] = True
            audio.sfx("kiss")
            self.fx.parts.append(dict(k="beijo", x=hx, y=hy, vx=0, vy=-14, life=1.5, c=None))
        if k["smack"] and t < W + L + H and random.random() < dt * 7:
            self.fx.parts.append(dict(k="beijo_p", x=hx + random.uniform(-16, 16), y=hy + random.uniform(-4, 8),
                                      vx=0, vy=random.uniform(-40, -24), life=random.uniform(0.7, 1.1), c=None,
                                      sway=random.uniform(0, 6)))
        if t >= W + L + H + B:
            self.kiss = None

    def finish(self):
        if self.finished:
            return
        self.finished = True
        self.done = True
        self.g.ambient.reset()
        if self.on_end:
            self.on_end()

    # ----- loop
    def handle(self, ev):
        if self.ask_skip:
            if ev.type == pygame.KEYDOWN:
                if ev.key in (pygame.K_e, pygame.K_RETURN, pygame.K_SPACE, pygame.K_s):
                    self.finish()
                elif ev.key in (pygame.K_ESCAPE, pygame.K_n, pygame.K_BACKSPACE):
                    self.ask_skip = False
            return
        if ev.type == pygame.KEYDOWN and ev.key == pygame.K_ESCAPE and not isinstance(self.sub, ui.Choice):
            self.ask_skip = True
            return
        if self.photo is not None:
            if ev.type == pygame.KEYDOWN and ev.key in ui.CONFIRM:
                self.photo = None
            return
        if self.sub:
            self.sub.handle(ev)
            if self.sub.done:
                self.sub = None
        elif self.caption and ev.type == pygame.KEYDOWN and ev.key in ui.CONFIRM:
            self.caption["t"] = min(self.caption["t"], 0.3)

    def update(self, dt):
        self.t += dt
        self.bars = min(1.0, self.bars + dt * 2.5)
        if self.fade_dir == 1:
            self.fade = min(1.0, self.fade + dt * 2.5)
            if self.fade >= 1:
                self.fade_dir = 0
                if self.after_fade:
                    cb, self.after_fade = self.after_fade, None
                    cb()
        elif self.fade_dir == -1:
            self.fade = max(0.0, self.fade - dt * 2.0)
            if self.fade <= 0:
                self.fade_dir = 0
        if self.sub:
            self.sub.update(dt)
        self.wait = max(0.0, self.wait - dt)
        if self.caption:
            self.caption["t"] -= dt
            if self.caption["t"] <= -0.4:
                self.caption = None
        for a in self.actors.values():
            a.update(dt)
        if self.kiss:
            self.update_kiss(dt)
        if self.follow and self.follow in self.actors:
            a = self.actors[self.follow]
            self.cam_target = self.tile_cam(a.fx, a.fy)
        if self.cam_target:
            k = min(1.0, dt * 2.2)
            self.cam[0] += (self.cam_target[0] - self.cam[0]) * k
            self.cam[1] += (self.cam_target[1] - self.cam[1]) * k
            if abs(self.cam_target[0] - self.cam[0]) < 2 and abs(self.cam_target[1] - self.cam[1]) < 2:
                self.cam = list(self.cam_target)
                if not self.follow:
                    self.cam_target = None
        self.fx.update(dt)
        self.g.ambient.update(dt, self.map, self.cam, self.minutes, self.weather)
        if not self.blocked():
            self.wait_actor = None
            self.wait_cam = False
        self.run_steps()

    def draw(self, surf):
        cam = (int(self.cam[0]) // 2 * 2, int(self.cam[1]) // 2 * 2)
        self.g.render_map(surf, self.map, cam, minutes=self.minutes, actors=list(self.actors.values()),
                          weather=self.weather, extra=self.fx)
        bh = int(BAR_H * (1 - (1 - self.bars) ** 2))
        if bh:
            pygame.draw.rect(surf, (0, 0, 0), (0, 0, SCREEN_W, bh))
            pygame.draw.rect(surf, (0, 0, 0), (0, SCREEN_H - bh, SCREEN_W, bh))
        if self.caption:
            c = self.caption
            k = min(1.0, max(0.0, min(c["total"] - c["t"], c["t"] + 0.4) / 0.4))
            img = ui.font(40, True).render(c["text"], False, C_TEXT)
            sh = ui.font(40, True).render(c["text"], False, (20, 10, 30))
            img.set_alpha(int(255 * k))
            sh.set_alpha(int(200 * k))
            x = SCREEN_W // 2 - img.get_width() // 2
            surf.blit(sh, (x + 3, SCREEN_H // 2 - 40 + 4))
            surf.blit(img, (x, SCREEN_H // 2 - 40))
        if self.fade > 0:
            veil = pygame.Surface((SCREEN_W, SCREEN_H))
            veil.set_alpha(int(255 * self.fade))
            surf.blit(veil, (0, 0))
        if self.sub:
            self.sub.draw(surf)
        if self.photo is not None:
            veil = pygame.Surface((SCREEN_W, SCREEN_H), pygame.SRCALPHA)
            veil.fill((10, 4, 20, 200))
            surf.blit(veil, (0, 0))
            r = self.photo.get_rect(center=(SCREEN_W // 2, SCREEN_H // 2 - 10))
            pygame.draw.rect(surf, (250, 246, 240), r.inflate(28, 60), border_radius=6)
            ui.blit_portrait(surf, self.photo, r.topleft)
            hrt = art.heart(True, 4)
            surf.blit(hrt, (r.centerx - hrt.get_width() // 2, r.bottom + 10))
        if bh > 20:
            ui.text(surf, "Esc: pular cena", (SCREEN_W - 20, bh - 26), 15, (120, 110, 140), right=True, shadow=False)
        if self.ask_skip:
            r = pygame.Rect(0, 0, 440, 120)
            r.center = (SCREEN_W // 2, SCREEN_H // 2)
            ui.panel(surf, r)
            ui.text(surf, "Pular esta cena?", (r.centerx, r.y + 22), 24, C_LILAC, bold=True, center=True)
            ui.text(surf, "E = pular     Esc = continuar assistindo", (r.centerx, r.y + 66), 17, C_MUTED, center=True)


